/// Rellena una plantilla con el estilo de Android: %1$s, %2$d, %1$.1f y %%.
String f(String plantilla, List<Object> valores) {
  final patron = RegExp(r'%(\d+)\$(?:\.(\d+))?([sdf])');
  final resultado = plantilla.replaceAllMapped(patron, (m) {
    final valor = valores[int.parse(m.group(1)!) - 1];
    if (m.group(3) == 'f') {
      return (valor as num).toStringAsFixed(int.parse(m.group(2) ?? '6'));
    }
    return '$valor';
  });
  return resultado.replaceAll('%%', '%');
}
